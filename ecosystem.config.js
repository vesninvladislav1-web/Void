// Настройки pm2 для Void.
//
// Зачем файлом, а не командой: сейчас они живут только в памяти pm2 на
// одной конкретной машине. При переезде, переустановке или чужих руках их
// пришлось бы вспоминать — а вспоминаются такие вещи всегда неправильно.
//
// ВНИМАНИЕ, прежде чем применять. Пароль администратора и ключ разборщика
// жалоб хранятся в отдельном хранилище pm2 (pm2 set void-signal:KEY ...),
// а не здесь и не в репозитории. Команда `pm2 delete` их не трогает, но
// проверить перед применением стоит — см. РАЗВЁРТЫВАНИЕ.md.
module.exports = {
  apps: [{
    name: 'void-signal',
    script: 'server/server.js',
    cwd: '/var/www/voidm.site',

    // Одного процесса достаточно и он обязателен: сервер держит соединения
    // в памяти и открытую базу SQLite. Двое начали бы драться за неё, а
    // человек, подключённый ко второму, не получал бы сообщений от первого.
    instances: 1,
    exec_mode: 'fork',

    autorestart: true,

    // Предел перезапусков. Без него получается так: битая миграция базы —
    // падение при старте — pm2 поднимает — снова падение, и так по кругу.
    // Лог растёт, процессор занят, и НИКТО НЕ ЗНАЕТ, потому что процесс
    // формально всё время «запускается».
    //
    // Теперь после десяти падений подряд pm2 сдаётся и помечает процесс
    // сломанным. Узнать об этом можно только от наблюдателя снаружи —
    // поэтому этот пункт без внешнего присмотра бессмыслен.
    max_restarts: 10,

    // Что считать «поднялся». Проживший меньше минуты не засчитывается как
    // удачный запуск — иначе счётчик выше обнулялся бы каждый раз и предел
    // не срабатывал бы никогда.
    min_uptime: '60s',

    // Пауза перед подъёмом растёт: 0.2с, 0.4с, 0.8с и так далее. Если
    // причина падения временная (кончилась память, отвалился диск), у
    // системы появляется время прийти в себя, а не падать в такт.
    exp_backoff_restart_delay: 200,

    // Утечка памяти — редкая, но если появится, лучше перезапуск, чем
    // убитая ядром машина. Измерено: сервер на холостом ходу занимает
    // около 65 МБ, при пятистах соединениях — около 150 МБ.
    max_memory_restart: '700M',

    // Время на корректное закрытие: сервер закрывает соединения и базу
    // сам, и обрывать его на середине — верный способ испортить файл.
    kill_timeout: 8000,

    // Метки времени в логе. Без них строчки «Uncaught exception» лежат
    // без даты, и понять, когда это было, невозможно.
    time: true,

    env: {
      NODE_ENV: 'production'
    }
  }]
};
